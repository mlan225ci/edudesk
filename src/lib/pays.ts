// Les écoles sont à l'étranger : le pays d'origine des étudiants n'est pas proposé.
export const PAYS = TOUS.filter((pays) => pays !== "Côte d'Ivoire").sort((a, b) => a.localeCompare(b, "fr"));

function normaliser(texte: string) {
  return texte.normalize("NFD").replace(/[\u0300-\u036f]/g, "").toLowerCase().trim();
}

// « France public » et « France privé » renvoient à la France ; on garde la correspondance la plus longue
// pour que « Guinée équatoriale » ne soit pas confondue avec « Guinée ».
export function paysDeDestination(destination: string) {
  const cible = normaliser(destination);
  let trouve: string | null = null;
  for (const pays of PAYS) {
    const nom = normaliser(pays);
    const correspond = cible === nom || (cible.startsWith(nom) && /[\s\-(]/.test(cible[nom.length] ?? ""));
    if (correspond && (!trouve || nom.length > normaliser(trouve).length)) trouve = pays;
  }
  return trouve;
}

export function paysDesProcedures(destinations: string[]) {
  return [...new Set(destinations.map(paysDeDestination).filter((pays): pays is string => Boolean(pays)))].sort((a, b) => a.localeCompare(b, "fr"));
}
